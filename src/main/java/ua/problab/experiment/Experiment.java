package ua.problab.experiment;

import java.util.List;
import java.util.random.RandomGenerator;

/** Випадковий експеримент: точна теорія + генерація випадкових наслідків. */
public interface Experiment {

    ExperimentConfig config();

    /** Точна ймовірність події A з поясненням. */
    Theory theory();

    /** Одне випадкове випробування. */
    Trial sample(RandomGenerator rnd);

    /** Найменше і найбільше значення статистики (для гістограми). */
    int statisticMin();

    int statisticMax();

    /** Подання наслідку для показу на екрані: "Г", "Ц", "5", "Ч", "С". */
    List<String> tokens(int[] raw);
}
