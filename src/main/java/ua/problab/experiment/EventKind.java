package ua.problab.experiment;

/** Подія A, ймовірність якої досліджується. */
public enum EventKind {
    // --- монети ---
    /** Рівно k гербів. */
    HEADS_EXACTLY,
    /** Не менше k гербів. */
    HEADS_AT_LEAST,
    /** Не більше k гербів. */
    HEADS_AT_MOST,
    /** Усі монети впали однаково. */
    COINS_ALL_SAME,
    /** Герб у кидку, що йде одразу після серії з r гербів (демонстрація «помилки гравця»). */
    HEADS_AFTER_STREAK,

    // --- кубики ---
    /** Сума очок дорівнює s. */
    SUM_EQ,
    /** Сума очок не менша за s. */
    SUM_AT_LEAST,
    /** Сума очок не більша за s. */
    SUM_AT_MOST,
    /** Сума очок парна. */
    SUM_EVEN,
    /** Хоча б на одному кубику випало v очок. */
    AT_LEAST_ONE_FACE,
    /** На всіх кубиках однакова кількість очок. */
    DICE_ALL_SAME,

    // --- урна ---
    /** Серед вийнятих куль рівно m червоних. */
    RED_EXACTLY,
    /** Серед вийнятих куль не менше m червоних. */
    RED_AT_LEAST,
    /** Усі вийняті кулі одного кольору. */
    URN_ALL_SAME
}
